#!/bin/sh
# Regenerates injected_script.js: Playwright's injected script as bundled in
# the patchright driver of the reference image (a string literal in coreBundle.js).
set -e
cd "$(dirname "$0")"
docker run --rm -i --user "$(id -u):$(id -g)" -e HOME=/tmp --entrypoint sh "${IMAGE:-parsers-autobrowser:latest}" -c \
	'D=/opt/venv/lib/python3.12/site-packages/patchright/driver; cat > /tmp/x.js; "$D/node" /tmp/x.js "$D/package"' \
	> injected_script.js <<'JS'
const fs = require('fs');
const dir = process.argv[2];
const version = JSON.parse(fs.readFileSync(dir + '/package.json', 'utf8')).version;
const line = fs.readFileSync(dir + '/lib/coreBundle.js', 'utf8').split('\n').find(l => l.trimStart().startsWith("source4 = '"));
const source = eval(line.trim().replace(/^source4 = /, '').replace(/;$/, ''));
process.stdout.write(`// Playwright injected script from patchright-core ${version}. Apache-2.0, see LICENSE.\n// Generated by extract.sh, do not edit.\n` + source);
JS
